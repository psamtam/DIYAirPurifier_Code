"""Generate matching main-firmware header, external image and loader header.

Usage: python tools/generate_ui_assets.py [--root package-directory]
Catalogue positions are stable IDs used by uiText() in the main sketch.
"""
import argparse,json,pathlib,struct

def make_image(texts):
    if not isinstance(texts,list) or not texts or len(texts)>119:
        raise ValueError('Catalogue must contain 1..119 text slots')
    encoded=[]
    for text in texts:
        if not isinstance(text,str) or '\0' in text:
            raise ValueError('Each slot must be a string without embedded NUL')
        b=text.encode('ascii')
        if len(b)>31: raise ValueError('Text exceeds 31 bytes: '+text)
        encoded.append(b.ljust(32,b'\0'))
    payload=b''.join(encoded)
    checksum=0xA55A
    for b in payload: checksum=(((checksum<<5)|(checksum>>11))^b)&0xffff
    image=struct.pack('<IHH',0x58545041,len(texts),checksum)+payload
    if 256+len(image)>4096: raise ValueError('AT24C32 capacity exceeded')
    return image,checksum

def generate(root):
    root=pathlib.Path(root)
    texts=json.loads((root/'ui-texts.json').read_text(encoding='utf-8'))
    image,checksum=make_image(texts)
    (root/'AirPurifier/UiAssets.h').write_text(
        '// Generated by tools/generate_ui_assets.py; do not edit.\n#pragma once\n#include <stdint.h>\n'
        f'const uint8_t UI_TEXT_COUNT = {len(texts)};\nconst uint16_t UI_TEXT_CHECKSUM = 0x{checksum:04X};\n')
    loader=root/'UiEepromProgrammer';loader.mkdir(exist_ok=True)
    rows=[', '.join(f'0x{b:02X}' for b in image[i:i+16]) for i in range(0,len(image),16)]
    (loader/'UiImage.h').write_text('// Generated; external EEPROM address 256.\n#pragma once\n#include <avr/pgmspace.h>\n'
        'const uint8_t UI_IMAGE[] PROGMEM = {\n  '+',\n  '.join(rows)+'\n};\n'
        'static_assert(sizeof(UI_IMAGE) + 256 <= 4096, "UI image exceeds AT24C32");\n')
    (root/'ui-assets.bin').write_bytes(image)
    summary={'base_address':256,'image_bytes':len(image),'end_exclusive':256+len(image),
             'free_eeprom_bytes':4096-256-len(image),'text_count':len(texts),'checksum':checksum}
    (root/'ui-assets-manifest.json').write_text(json.dumps(summary,indent=2)+'\n')
    print(json.dumps(summary))
    return image

if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--root',type=pathlib.Path,default=pathlib.Path(__file__).resolve().parents[1])
    generate(p.parse_args().root)
